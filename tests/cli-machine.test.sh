#!/usr/bin/env bash
# scripts/dotfiles.sh machine: --json, `set` (quoting, unset, list, bool,
# validation, other keys untouched, unsafe shapes refused) and `apply` (no
# --force, the playbook's forced apply skipped). ansible and chezmoi are stubs.
# shellcheck disable=SC2016,SC2088 # stub bodies run later; ~ paths are literal values
set -uo pipefail
# shellcheck source=lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

script="$TESTS_REPO/scripts/dotfiles.sh"
mk_home
mkdir -p "$HOME/bin"
real_bin() {
	local d IFS=:
	for d in $PATH; do
		case "$d" in */shims | */shims/) continue ;; esac
		[ -x "$d/$1" ] && {
			echo "$d/$1"
			return 0
		}
	done
	return 1
}
for t in yq jq; do
	real_bin "$t" >/dev/null || {
		[ -z "${CI:-}" ] || fail "no non-shim $t on PATH (CI must not skip)"
		echo "SKIP: no non-shim $t on PATH" >&2
		exit 0
	}
	ln -s "$(real_bin "$t")" "$HOME/bin/$t"
done
export STUB_CALL="$HOME/call.txt"
printf '#!/bin/sh\necho "ansible-playbook $*" >>"$STUB_CALL"\n' >"$HOME/bin/ansible-playbook"
printf '#!/bin/sh\necho "chezmoi $*" >>"$STUB_CALL"\n' >"$HOME/bin/chezmoi"
chmod +x "$HOME/bin/"*
yml="$HOME/local.yml"

reset_yml() {
	cat >"$yml" <<'Y'
---
# Generated by install.sh.
git_name: 'Ola'
git_email: 'ola@example.com'
allow_sudo: true
tool_groups: [git, dev] # mine
Y
}
run() { # run ARGS...: sets out, rc
	out="$(env -i HOME="$HOME" PATH="$HOME/bin:/usr/bin:/bin" STUB_CALL="$STUB_CALL" DOTFILES_LOCAL_YML="$yml" \
		sh "$script" "$@" 2>&1 </dev/null)"
	rc=$?
}
val() { yq -o=json -I0 ".$1" "$yml"; }

# machine_json
reset_yml
printf 'ssh-ed25519 AAAA x\n' >"$HOME/k.pub"
run machine set signing_key "~/k.pub" --no-apply
run machine --json
assert_eq 0 "$rc" "machine --json: exit 0 ($out)"
assert_eq '"Ola"' "$(jq -c .values.git_name <<<"$out")" "machine --json: git_name"
assert_eq 'null' "$(jq -c .values.personal_git_email <<<"$out")" "machine --json: unset key is null"
assert_eq '["git","dev"]' "$(jq -c .values.tool_groups <<<"$out")" "machine --json: tool selection shown"
assert_eq '{"key":"~/k.pub","exists":true}' "$(jq -c .signing <<<"$out")" "machine --json: signing key file found"

# set_scalars: quoted, other keys and comments untouched
reset_yml
run machine set git_name "O'Brien: Ola" --no-apply
assert_eq 0 "$rc" "set git_name: exit 0 ($out)"
assert_eq '"O'"'"'Brien: Ola"' "$(val git_name)" "set git_name: quotes and colons round-trip"
assert_contains "$(cat "$yml")" "tool_groups: [git, dev] # mine" "set: other lines untouched"
assert_contains "$(cat "$yml")" "# Generated by install.sh." "set: comments kept"
run machine set personal_git_email "me@users.noreply.github.com" --no-apply
assert_eq '"me@users.noreply.github.com"' "$(val personal_git_email)" "set: an absent key is appended"
run machine set personal_git_dirs "~/workspace/dotfiles/, ~/personal/" --no-apply
assert_eq '["~/workspace/dotfiles/","~/personal/"]' "$(val personal_git_dirs)" "set: personal_git_dirs from a comma list"
run machine set allow_sudo false --no-apply
assert_eq 'false' "$(val allow_sudo)" "set allow_sudo: a real boolean"
run machine set personal_git_email "" --no-apply
assert_eq 'null' "$(val personal_git_email)" "set: an empty value removes the key"

# set_validation: nothing is written on a bad value
reset_yml
before="$(cat "$yml")"
for args in "git_email|" "allow_sudo|maybe" "signing_key|~/.ssh/id_ed25519" "shared_home|true" "tool_groups|git" "nope|x"; do
	run machine set "${args%%|*}" "${args#*|}" --no-apply
	assert_eq 2 "$rc" "set ${args%%|*}=${args#*|}: refused"
done
assert_eq "$before" "$(cat "$yml")" "refused sets leave local.yml byte-identical"

# set_unsafe_shape: a block value under the key is not edited
printf 'git_name:\n  - weird\n' >>"$yml"
before="$(cat "$yml")"
run machine set git_name X --no-apply
assert_eq 2 "$rc" "set on a duplicated/block key: refused"
assert_eq "$before" "$(cat "$yml")" "unsafe shape: local.yml unchanged"

# apply: config rewrite without the forced apply, then a plain chezmoi apply
reset_yml
rm -f "$STUB_CALL"
run machine set git_name Ola2
assert_eq 0 "$rc" "set + apply: exit 0 ($out)"
calls="$(cat "$STUB_CALL")"
assert_contains "$calls" "ansible-playbook site.yml --tags chezmoi --skip-tags packages,chezmoi_apply" "apply: playbook skips its forced apply"
assert_contains "$calls" "chezmoi --no-pager --no-tty apply" "apply: chezmoi apply without a tty"
assert_not_contains "$calls" "--force" "apply: never --force"

# other_checkout: a second checkout (no local.yml of its own) reads and edits
# the machine's local.yml beside chezmoi's source, but never runs the playbook
# (it would point chezmoi's sourceDir at itself).
co="$HOME/co" main="$HOME/main"
mkdir -p "$co/scripts" "$main/home" "$main/ansible" "$HOME/obin"
cp "$script" "$TESTS_REPO/scripts/mise-env.sh" "$co/scripts/"
reset_yml
cp "$yml" "$main/ansible/local.yml"
printf '#!/bin/sh\n[ "$1" = source-path ] && echo "%s/home"\necho "chezmoi $*" >>"$STUB_CALL"\n' "$main" >"$HOME/obin/chezmoi"
printf '#!/bin/sh\necho "ansible-playbook $*" >>"$STUB_CALL"\n' >"$HOME/obin/ansible-playbook"
chmod +x "$HOME/obin/"*
orun() { # orun ARGS...: the copy in $co, chezmoi's source in $main
	out="$(env -i HOME="$HOME" PATH="$HOME/obin:$HOME/bin:/usr/bin:/bin" STUB_CALL="$STUB_CALL" sh "$co/scripts/dotfiles.sh" "$@" 2>&1 </dev/null)"
	rc=$?
}
orun machine --json
assert_eq "$main/ansible/local.yml" "$(jq -r .path <<<"$out")" "other checkout: reads the machine's local.yml"
orun machine set git_name Other --no-apply
assert_eq '"Other"' "$(yq -o=json '.git_name' "$main/ansible/local.yml")" "other checkout: edits the machine's local.yml"
rm -f "$STUB_CALL"
orun machine apply
assert_eq 1 "$rc" "other checkout: machine apply refused"
assert_contains "$out" "run it from $main" "other checkout: says where to run it"
assert_not_contains "$(cat "$STUB_CALL" 2>/dev/null)" "ansible-playbook" "other checkout: the playbook never ran"
